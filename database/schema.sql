-- Схема БД каталога чемоданов. MySQL 5.7+/8.0, MariaDB 10.4+. Кодировка utf8mb4.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS categories (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  h1 VARCHAR(200) NOT NULL DEFAULT '',
  meta_title VARCHAR(200) NOT NULL DEFAULT '',
  meta_description VARCHAR(320) NOT NULL DEFAULT '',
  intro TEXT NULL,
  sort INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS products (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(160) NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL,
  category_id INT UNSIGNED NULL,
  brand VARCHAR(80) NOT NULL DEFAULT '',
  sku VARCHAR(60) NOT NULL DEFAULT '',
  price INT UNSIGNED NOT NULL DEFAULT 0,
  old_price INT UNSIGNED NULL,
  size_label VARCHAR(10) NOT NULL DEFAULT 'M',
  material VARCHAR(60) NOT NULL DEFAULT '',
  color VARCHAR(60) NOT NULL DEFAULT '',
  color_hex CHAR(7) NOT NULL DEFAULT '#555555',
  width_cm DECIMAL(5,1) NULL,
  height_cm DECIMAL(5,1) NULL,
  depth_cm DECIMAL(5,1) NULL,
  volume_l DECIMAL(5,1) NULL,
  weight_kg DECIMAL(4,2) NULL,
  wheels TINYINT UNSIGNED NOT NULL DEFAULT 4,
  lock_type VARCHAR(60) NOT NULL DEFAULT '',
  expandable TINYINT(1) NOT NULL DEFAULT 0,
  warranty_months SMALLINT UNSIGNED NOT NULL DEFAULT 12,
  short_desc VARCHAR(300) NOT NULL DEFAULT '',
  description TEXT NULL,
  meta_title VARCHAR(200) NOT NULL DEFAULT '',
  meta_description VARCHAR(320) NOT NULL DEFAULT '',
  in_stock TINYINT(1) NOT NULL DEFAULT 1,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  sort INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_active (is_active, sort),
  KEY idx_cat (category_id),
  KEY idx_price (price),
  CONSTRAINT fk_prod_cat FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS product_images (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id INT UNSIGNED NOT NULL,
  file VARCHAR(120) NOT NULL,
  width SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  height SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  alt VARCHAR(200) NOT NULL DEFAULT '',
  sort INT NOT NULL DEFAULT 0,
  KEY idx_prod (product_id, sort),
  CONSTRAINT fk_img_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cities (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  name_in VARCHAR(100) NOT NULL,          -- «в Алматы», «в Астане»
  delivery_days VARCHAR(40) NOT NULL DEFAULT '1–3 дня',
  delivery_text TEXT NULL,
  meta_title VARCHAR(200) NOT NULL DEFAULT '',
  meta_description VARCHAR(320) NOT NULL DEFAULT '',
  intro TEXT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  sort INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS leads (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  type VARCHAR(30) NOT NULL DEFAULT 'callback',
  name VARCHAR(100) NOT NULL DEFAULT '',
  phone VARCHAR(20) NOT NULL,
  message VARCHAR(1000) NOT NULL DEFAULT '',
  product_id INT UNSIGNED NULL,
  city VARCHAR(80) NOT NULL DEFAULT '',
  page_url VARCHAR(500) NOT NULL DEFAULT '',
  utm VARCHAR(500) NOT NULL DEFAULT '',
  ip VARCHAR(45) NOT NULL DEFAULT '',
  user_agent VARCHAR(300) NOT NULL DEFAULT '',
  consent_at DATETIME NOT NULL,
  consent_version VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'new',
  admin_note VARCHAR(1000) NOT NULL DEFAULT '',
  tg_sent TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_status (status, created_at),
  CONSTRAINT fk_lead_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(60) PRIMARY KEY,
  v TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  login VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  last_login_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rate_limits (
  rkey VARCHAR(120) PRIMARY KEY,
  hits INT UNSIGNED NOT NULL DEFAULT 0,
  window_start INT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
